// Builds a trimmed Font Awesome: only icons used by the site (views, code, seeds)
// plus the admin icon list in resources/icons.json. Run: npm run icons
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import subsetFont from 'subset-font';

const FA = 'node_modules/@fortawesome/fontawesome-free';
const css = readFileSync(`${FA}/css/all.min.css`, 'utf8');

// icon name -> codepoint, e.g. heart -> f004 (rules may list several aliases)
const codepoints = {};
for (const [, selectors, cp] of css.matchAll(/((?:\.fa-[a-z0-9-]+:before,?)+)\{content:"\\([0-9a-f]+)"\}/g)) {
    for (const [, name] of selectors.matchAll(/\.fa-([a-z0-9-]+):before/g)) codepoints[name] = cp;
}

const used = new Set();
const scan = (dir) => {
    for (const entry of readdirSync(dir)) {
        const path = join(dir, entry);
        if (statSync(path).isDirectory()) scan(path);
        else if (/\.(php|js|json)$/.test(entry)) {
            for (const [, name] of readFileSync(path, 'utf8').matchAll(/fa-([a-z0-9-]+)/g)) used.add(name);
        }
    }
};
['resources/views', 'resources/js', 'app', 'database/seeders'].forEach(scan);
Object.keys(JSON.parse(readFileSync('resources/icons.json', 'utf8'))).forEach((k) => k.split(' ').forEach((c) => used.add(c.replace(/^fa-/, ''))));

const icons = [...used].filter((n) => codepoints[n]).sort();
const text = String.fromCodePoint(...new Set(icons.map((n) => parseInt(codepoints[n], 16))));

const fonts = { solid: 'fa-solid-900', regular: 'fa-regular-400', brands: 'fa-brands-400' };
for (const [key, file] of Object.entries(fonts)) {
    const subset = await subsetFont(readFileSync(`${FA}/webfonts/${file}.woff2`), text, { targetFormat: 'woff2' });
    writeFileSync(`resources/fonts/fa-${key}.woff2`, subset);
    console.log(`fa-${key}.woff2: ${(subset.length / 1024).toFixed(1)} KB`);
}

const face = (family, weight, file) =>
    `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url(../fonts/${file}.woff2) format("woff2")}`;

writeFileSync('resources/css/icons.css', [
    '/* Generated by scripts/build-icons.mjs — do not edit. */',
    face('Font Awesome 6 Free', 900, 'fa-solid'),
    face('Font Awesome 6 Free', 400, 'fa-regular'),
    face('Font Awesome 6 Brands', 400, 'fa-brands'),
    '.fa,.fa-solid,.fa-regular,.fa-brands{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:inline-block;font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}',
    '.fa,.fa-solid{font-family:"Font Awesome 6 Free";font-weight:900}',
    '.fa-regular{font-family:"Font Awesome 6 Free";font-weight:400}',
    '.fa-brands{font-family:"Font Awesome 6 Brands";font-weight:400}',
    ...icons.map((n) => `.fa-${n}:before{content:"\\${codepoints[n]}"}`),
].join('\n') + '\n');
console.log(`${icons.length} icons`);
